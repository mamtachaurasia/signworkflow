const variable = (key, label, required = true, defaultValue = '') => ({
  key,
  label,
  required,
  defaultValue,
});

const title = (id, text) => ({ id, type: 'title', text, align: 'center', bold: true, italic: false });
const heading = (id, text) => ({ id, type: 'heading', text, align: 'left', bold: true, italic: false });
const paragraph = (id, text, options = {}) => ({
  id,
  type: 'paragraph',
  text,
  align: options.align || 'left',
  bold: options.bold === true,
  italic: options.italic === true,
});
const listItem = (id, text) => ({ id, type: 'list-item', text, align: 'left', bold: false, italic: false });
const table = (id, rows) => ({ id, type: 'table', text: '', table: { rows }, align: 'left' });
const pageBreak = (id) => ({ id, type: 'page-break', text: '', align: 'left', bold: false, italic: false });

function standardExecutionBlocks(prefix, roleLabels) {
  return [
    pageBreak(`${prefix}-execution-page-break`),
    heading(`${prefix}-execution-heading`, 'Execution'),
    paragraph(
      `${prefix}-execution-note`,
      'The parties may sign this document electronically and in counterparts. Each signed counterpart is treated as an original to the extent permitted by applicable law.',
      { italic: true }
    ),
    ...roleLabels.flatMap(([roleId, roleLabel]) => [
      heading(`${prefix}-${roleId}-execution-heading`, roleLabel),
      paragraph(`${prefix}-${roleId}-execution-copy`, 'Authorised signature, name, and date appear in the signing fields below.'),
    ]),
  ];
}

